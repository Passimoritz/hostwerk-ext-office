/** innermost function call around the caret: { name, arg } (arg = 0-based index) */
export function callAt(text, caret, seps = ',;') {
  let depth = 0; let arg = 0; let inStr = false;
  for (let i = caret - 1; i >= 0; i--) {
    const ch = text[i];
    if (ch === '"') { inStr = !inStr; continue; }
    if (inStr) continue;
    if (ch === ')') depth++;
    else if (ch === '(') {
      if (depth === 0) { const m = /([A-Za-z_À-￿][\wÀ-￿.]*)\s*$/.exec(text.slice(0, i)); return m ? { name: m[1].toUpperCase(), arg } : null; }
      depth--;
    } else if (seps.includes(ch) && depth === 0) arg++;
  }
  return null;
}
